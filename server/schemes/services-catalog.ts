// Helper to find a matching service by query or id
export function findMatchingService(query: string): ServiceDefinition | null {
  const q = query.toLowerCase();
  
  if (q.includes('gas') || q.includes('ujjwala') || q.includes('cylinder') || q.includes('stove') || q.includes('గ్యాస్') || q.includes('ఉజ్జ్వల') || q.includes('गैस') || q.includes('उज्ज्वला') || q.includes('எரிவாயு') || q.includes('உஜ்வாலா') || q.includes('ಗ್ಯಾಸ್') || q.includes('ಉಜ್ವಲ')) {
    return SERVICES_CATALOG.find(s => s.id === 'pm-ujjwala') || null;
  }
  if (q.includes('ration') || q.includes('food') || q.includes('రేషన్') || q.includes('రాషన్') || q.includes('राशन') || q.includes('ரேஷன்') || q.includes('ಪಡಿತರ') || q.includes('റേഷൻ')) {
    return SERVICES_CATALOG.find(s => s.id === 'ration-card') || null;
  }
  if (q.includes('tailor') || q.includes('skill') || q.includes('course') || q.includes('నైపుణ్య') || q.includes('టైలరింగ్') || q.includes('सिलाई') || q.includes('कौशल') || q.includes('தையல்') || q.includes('ತರಬೇತಿ')) {
    return SERVICES_CATALOG.find(s => s.id === 'pmkvy-skills') || null;
  }
  if (q.includes('didi') || q.includes('shg') || q.includes('self help') || q.includes('group') || q.includes('డ్వాక్రా') || q.includes('స్వయం సహాయక') || q.includes('समूह') || q.includes('महिला') || q.includes('लखपति')) {
    return SERVICES_CATALOG.find(s => s.id === 'lakhpati-didi') || null;
  }
  if (q.includes('bank') || q.includes('jan dhan') || q.includes('account') || q.includes('zero balance') || q.includes('ఖాతా') || q.includes('బ్యాంక్') || q.includes('खाता') || q.includes('जन धन')) {
    return SERVICES_CATALOG.find(s => s.id === 'pm-jan-dhan') || null;
  }

  return null;
}

// Convert ServiceDefinition into StructuredGuidance for a specific language
export function getStructuredGuidance(service: ServiceDefinition, lang: SupportedLanguage): StructuredGuidance {
  return {
    serviceId: service.id,
    serviceName: service.names[lang] || service.officialName,
    category: service.category,
    whatItIs: service.whatItIs[lang] || service.whatItIs.en,
    whoIsEligible: service.whoIsEligible[lang] || service.whoIsEligible.en,
    documentsRequired: service.documentsRequired[lang] || service.documentsRequired.en,
    steps: service.steps[lang] || service.steps.en,
    whereToApply: service.whereToApply[lang] || service.whereToApply.en,
    officialSource: {
      name: service.officialName,
      url: service.officialUrl,
      helpline: service.helpline,
    },
    nextStep: service.nextStep[lang] || service.nextStep.en,
  };
}
